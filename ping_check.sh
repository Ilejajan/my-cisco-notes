#!/bin/bash

# 1. Создаем переменную с IP-адресом
SERVER="8.8.8.8"

# 2. Пишем красивый текст в консоль
echo "Проверяем доступность сервера $SERVER..."

# 3. Делаем 3 пинга и проверяем результат
if ping -c 3 $SERVER; then
    echo "Ура! Сервер $SERVER отвечает, сеть работает!"
else
    echo "ВНИМАНИЕ! Сервер $SERVER недоступен! Проверь маршруты!"
fi
