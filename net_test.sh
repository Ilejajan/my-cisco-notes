#!/bin/bash

# 1. Задаем хост для проверки (можно поменять на любой сайт)
TARGET="google.com"
DNS_SERVER="8.8.8.8"

echo "=================================================="
echo " НАЧАЛО ДИАГНОСТИКИ СЕТИ ДЛЯ УЗЛА: $TARGET"
echo "=================================================="
echo ""

# ШАГ 1: Проверка работы DNS (разрешение имени в IP)
echo "[1/3] Проверяем DNS-разрешение имен для $TARGET..."
if nslookup $TARGET > /dev/null 2>&1; then
    echo "🟢 DNS работает отлично! IP-адрес для $TARGET успешно найден."
else
    echo "🔴 ОШИБКА DNS: Не удалось определить IP-адрес для $TARGET."
    echo "Попробуем запросить напрямую через публичный DNS ($DNS_SERVER)..."
    nslookup $TARGET $DNS_SERVER
fi
echo "--------------------------------------------------"

# ШАГ 2: Проверка доступности узла (Пинг)
echo "[2/3] Запускаем пинг до $TARGET..."
if ping -n 3 $TARGET; then
    echo "🟢 Узел $TARGET доступен, пакеты доходят без потерь."
else
    echo "🔴 Узел $TARGET НЕ отвечает! Проблема на линии или хост лежит."
fi
echo "--------------------------------------------------"

# ШАГ 3: Поиск места обрыва (Трассировка маршрута)
echo "[3/3] Запускаем трассировку маршрута до $TARGET..."
echo "Это может занять около минуты, подожди..."
tracert -d -h 10 $TARGET  # -d отключает разрешение имен для скорости, -h 10 — макс. 10 прыжков
echo "--------------------------------------------------"

echo "=================================================="
echo " ДИАГНОСТИКА ЗАВЕРШЕНА!"
echo "=================================================="
